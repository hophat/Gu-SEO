/**
 * Chrome strings for one brand language. A key a language does not
 * translate falls back to the English base.
 */
export function ui(language) {
  const code = String(language || '').trim().toLowerCase().split(/[-_]/)[0];
  return { ...EN, ...(DICT[code] || {}) };
}

/** Substitute {name}-style placeholders. Unknown placeholders stay as-is. */
export function fmt(template, vars = {}) {
  return String(template).replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m));
}

/** Post count in the language's own wording, one vs many. */
export function countArticles(t, n) {
  return fmt(n === 1 ? t.posts_count_one : t.posts_count_many, { n });
}
